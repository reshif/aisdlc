import { describe, expect, it } from 'vitest';
import { AGENT_DEFINITIONS } from '../src/registry.js';

// The registry as JSON for external consumers (the portal, the eval harness): every definition with
// its contract (input and output JSON Schema, tools, limits) and prompt reference.

describe('generated/agents.json', () => {
  it('matches the registry (regenerate with `npm run gen -w @aisdlc/agents`)', async () => {
    const doc = {
      $comment: 'generated by `npm run gen -w @aisdlc/agents`; do not edit',
      agents: AGENT_DEFINITIONS,
    };
    await expect(`${JSON.stringify(doc, null, 2)}\n`).toMatchFileSnapshot(
      '../generated/agents.json',
    );
  });
});
