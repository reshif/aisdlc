import {
  ACTION_CATALOGUE,
  ACTION_IDS,
  PDP_POLICY_VERSION,
  ROLES_VERSION,
  ROLE_CATALOGUE,
  actionDef,
  policyBundleHash,
  roleGrants,
  type ActionDef,
  type ActionId,
  type PolicyBundle,
  type RoleDef,
} from '@aisdlc/contracts';

// Generation of the Cedar schema and policies (PLAN M4.3). The role policies come from the role
// catalogue and the action catalogue and nothing else: `roleGrants` says which actions a role
// holds, this file only spells them in Cedar. Three hand-written policies carry the rules that cut
// across roles. The output is deterministic (catalogue order, no clock, no randomness) and a test
// compares it with the committed files in `packages/pdp/generated/`.

type Actions = Readonly<Record<string, ActionDef>>;
const DEFAULT_ACTIONS = ACTION_CATALOGUE as unknown as Actions;

const str = (s: string): string => JSON.stringify(s);

/** The Cedar schema: the entity model and one action per catalogue entry. */
export function generateSchema(actions: Actions = DEFAULT_ACTIONS): string {
  const lines = [
    '// Generated by @aisdlc/pdp from the action catalogue. Do not edit.',
    '// A request is a Principal, an action and one resource. The principal is in a Role entity for',
    '// every binding that covers the resource, and in the Group that binding comes through.',
    'entity Role;',
    'entity Group;',
    'entity Principal in [Group, Role] = { "kind": String, "status": String, "breakglass": Bool };',
    'entity Fleet;',
    'entity Team in [Fleet];',
    'entity Project in [Fleet];',
    'entity Lane in [Project];',
    'entity Repo in [Project];',
    'entity Item in [Lane, Project];',
    'entity Gate in [Item, Lane, Project] = { "gate_id": String, "slot": String, "family": String };',
    'entity Card in [Item, Lane, Project];',
    '',
  ];
  for (const id of Object.keys(actions)) {
    const a = actions[id] as ActionDef;
    lines.push(
      `action ${str(id)} appliesTo { principal: [Principal], resource: [${a.resource_types.join(', ')}] };`,
    );
  }
  return `${lines.join('\n')}\n`;
}

const policyText = (annotation: string, body: string): string => `@id(${str(annotation)})\n${body}`;

/** `role/<role>/<action>` */
export const rolePolicyId = (role: string, action: string): string => `role/${role}/${action}`;

/** The cross-cutting policies, by id. They are the only hand-written policies. */
export const CROSS_CUTTING_POLICY_IDS = {
  disabled: 'xcut/disabled_principal_denied',
  service_decide: 'xcut/service_principal_never_decides',
  fleet_kill: 'xcut/fleet_kill_factory_admin_only',
} as const;

function crossCutting(actions: Actions): Record<string, string> {
  const ofClass = (c: ActionDef['class']): string =>
    Object.keys(actions)
      .filter((id) => (actions[id] as ActionDef).class === c)
      .map((id) => `Action::${str(id)}`)
      .join(', ');
  const out: Record<string, string> = {};
  out[CROSS_CUTTING_POLICY_IDS.disabled] = policyText(
    CROSS_CUTTING_POLICY_IDS.disabled,
    'forbid (principal, action, resource)\nwhen { principal.status != "active" };',
  );
  out[CROSS_CUTTING_POLICY_IDS.service_decide] = policyText(
    CROSS_CUTTING_POLICY_IDS.service_decide,
    `forbid (principal, action in [${ofClass('decide')}], resource)\nwhen { principal.kind == "service" };`,
  );
  out[CROSS_CUTTING_POLICY_IDS.fleet_kill] = policyText(
    CROSS_CUTTING_POLICY_IDS.fleet_kill,
    `forbid (principal, action in [${ofClass('kill')}], resource is Fleet)\nunless { principal in Role::"factory.admin" };`,
  );
  return out;
}

/** The policies by id: one `permit` per (role, action) the catalogue grants, then the three rules. */
export function generatePolicies(
  catalogue: readonly RoleDef[] = ROLE_CATALOGUE,
  actions: Actions = DEFAULT_ACTIONS,
): Record<string, string> {
  const out: Record<string, string> = {};
  for (const role of catalogue) {
    for (const g of roleGrants(role, actions)) {
      const id = rolePolicyId(role.role_id, g.action);
      const head = `permit (principal in Role::${str(role.role_id)}, action == Action::${str(g.action)}, resource)`;
      out[id] = policyText(
        id,
        g.gate_slot === null
          ? `${head};`
          : `${head}\nwhen { resource.slot == ${str(g.gate_slot)} };`,
      );
    }
  }
  return { ...out, ...crossCutting(actions) };
}

/** `pdp-<policy version>.roles-<roles version>`: any change to either changes the bundle version. */
export const BUNDLE_VERSION = `pdp-${PDP_POLICY_VERSION}.roles-${ROLES_VERSION}`;

/** The bundle for the current catalogues. */
export function buildBundle(
  o: {
    catalogue?: readonly RoleDef[];
    actions?: Actions;
    bundle_version?: string;
  } = {},
): PolicyBundle {
  const actions = o.actions ?? DEFAULT_ACTIONS;
  const base = {
    schema: generateSchema(actions),
    policies: generatePolicies(o.catalogue ?? ROLE_CATALOGUE, actions),
    bundle_version: o.bundle_version ?? BUNDLE_VERSION,
  };
  return { ...base, bundle_hash: policyBundleHash(base) };
}

/** Policy ids in the bundle that grant `role` its actions (for explain and tests). */
export const actionsOfPolicies = (policies: Record<string, string>, role: string): ActionId[] =>
  ACTION_IDS.filter((a) => rolePolicyId(role, a) in policies && actionDef(a) !== undefined);
