import { readFileSync } from 'node:fs';
import { join } from 'node:path';
import { describe, expect, it } from 'vitest';
import { parse } from 'yaml';

// PLAN M10.1: "no other container can read the key file". The file is a compose secret, so it is
// mounted only where a service lists it; this test reads the stack's own definition and checks that
// only the gateway lists it, that nothing else reaches the file by a bind mount or an environment
// variable, and that the gateway's networks are the narrow set the review (RV §2) asks for. The same
// facts are checked on the RUNNING stack by `smoke.sh`.

const dir = join(import.meta.dirname, '..', '..', '..', 'platform', 'compose');
interface Service {
  secrets?: Array<string | { source: string }>;
  volumes?: Array<string | { source?: string; target?: string }>;
  environment?: Record<string, string> | string[];
  networks?: string[] | Record<string, unknown>;
  network_mode?: string;
  healthcheck?: { test?: string[] };
  depends_on?: Record<string, { condition: string }>;
  user?: string;
  read_only?: boolean;
  cap_drop?: string[];
}
const compose = parse(readFileSync(join(dir, 'docker-compose.yml'), 'utf8'), { merge: true }) as {
  services: Record<string, Service>;
  secrets: Record<string, { file: string }>;
  networks: Record<string, { internal?: boolean } | null>;
};
const KEY = 'anthropic-api-key';
const names = (s: Service): string[] =>
  Array.isArray(s.networks) ? s.networks : Object.keys(s.networks ?? {});
const secretsOf = (s: Service): string[] =>
  (s.secrets ?? []).map((x) => (typeof x === 'string' ? x : x.source));
const envText = (s: Service): string =>
  JSON.stringify(s.environment ?? {}) + JSON.stringify(s.volumes ?? []);

describe('the vendor key in the compose stack', () => {
  const others = Object.entries(compose.services).filter(([n]) => n !== 'gateway');

  it('is one file secret, generated by init-secrets and kept out of git', () => {
    expect(compose.secrets[KEY]).toEqual({ file: `./secrets/${KEY}` });
    expect(readFileSync(join(dir, 'init-secrets'), 'utf8')).toContain('secrets/anthropic-api-key');
    const gitignore = readFileSync(join(dir, '.gitignore'), 'utf8');
    expect(gitignore).toMatch(/^secrets\/\*$/m);
  });

  it('is mounted into the gateway and into no other service', () => {
    expect(secretsOf(compose.services['gateway']!)).toContain(KEY);
    for (const [name, svc] of others) {
      expect(secretsOf(svc), `${name} mounts the vendor key`).not.toContain(KEY);
    }
  });

  it('is reachable by no other service through a bind mount, an env var or the secrets directory', () => {
    for (const [name, svc] of others) {
      expect(envText(svc), `${name} names the key`).not.toMatch(
        /anthropic[-_]api[-_]key|ANTHROPIC_API_KEY/i,
      );
      for (const v of svc.volumes ?? []) {
        const src = typeof v === 'string' ? v.split(':')[0] : v.source;
        expect(src ?? '', `${name} mounts the secrets directory`).not.toMatch(/secrets\/?$/);
      }
    }
    // and the gateway itself takes the key as a file reference, never a literal or an env var
    const env = compose.services['gateway']!.environment as Record<string, string>;
    expect(JSON.stringify(env)).toContain('file:/run/secrets/anthropic-api-key');
    expect(JSON.stringify(env)).not.toMatch(/ANTHROPIC_API_KEY/);
  });

  it('gives the gateway its own egress network and no network of the trust plane', () => {
    const gw = names(compose.services['gateway']!);
    expect(gw).toContain('gateway-egress');
    expect(compose.networks['gateway-egress']?.internal).not.toBe(true);
    const forbidden = gw.filter((n) =>
      /^(kms-|notary|witness|app$|edge$|egress$|data-(record|notary|witness|killswitch))/.test(n),
    );
    expect(forbidden).toEqual([]);
    // only Postgres shares its database network
    const onData = Object.entries(compose.services)
      .filter(([, svc]) => names(svc).includes('data-gateway'))
      .map(([n]) => n);
    expect(onData.sort()).toEqual(['gateway', 'postgres']);
    // nobody else is on its egress or its API network
    for (const [name, svc] of others) {
      expect(names(svc), `${name} is on the gateway's egress`).not.toContain('gateway-egress');
      expect(names(svc), `${name} is on the gateway's API network`).not.toContain('gateway-api');
    }
    // the only service sharing its kill switch link is the kill switch
    const onLink = others
      .filter(([, svc]) => names(svc).includes('killswitch-gateway'))
      .map(([n]) => n);
    expect(onLink).toEqual(['killswitch']);
    expect(compose.networks['gateway-api']?.internal).toBe(true);
    expect(compose.networks['killswitch-gateway']?.internal).toBe(true);
    expect(compose.services['gateway']!.network_mode).toBeUndefined();
  });

  it('runs the gateway like every service: a health check, after the migration, read-only, no capabilities', () => {
    const gw = compose.services['gateway']!;
    expect(gw.healthcheck?.test?.join(' ')).toContain('8410');
    expect(gw.depends_on?.['migrate']?.condition).toBe('service_completed_successfully');
    expect(gw.depends_on?.['killswitch']?.condition).toBe('service_healthy');
    expect(gw.read_only).toBe(true);
    expect(gw.cap_drop).toEqual(['ALL']);
  });

  it('keeps the other services away from the gateway: only the kill switch grants it a token', () => {
    const ks = compose.services['killswitch']!.environment as Record<string, string>;
    expect(ks['KILLSWITCH_CALLERS']).toMatch(/"gateway":\{[^}]*"scopes":\["read"\]/);
  });
});
